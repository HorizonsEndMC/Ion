    fun getDistance(c1: Color, c2: Color): Double {
        val rsum = c1.red + c2.red
        val r = c1.red - c2.red
        val g = c1.green - c2.green
        val b = c1.blue - c2.blue
        val weightR = 1024 + rsum
        val weightG = 2048
        val weightB = 1024 + (510 - rsum)
        return (weightR * r * r + weightG * g * g + weightB * b * b).toDouble()
    }

    fun getDistance(c1: org.bukkit.Color, c2: Color): Double {
        val rsum = c1.red + c2.red
        val r = c1.red - c2.red
        val g = c1.green - c2.green
        val b = c1.blue - c2.blue
        val weightR = 1024 + rsum
        val weightG = 2048
        val weightB = 1024 + (510 - rsum)
        return (weightR * r * r + weightG * g * g + weightB * b * b).toDouble()
    }

    fun matchColor(color: org.bukkit.Color): Byte {
        if (color.alpha < 128) {
            return 0
        }
        else {
            var index = 0
            var best = -1.0

            for (i in 4..colors.size) {
                val distance = getDistance(color, colors[i])
                if (distance < best || best == -1.0) {
                    best = distance
                    index = i
                }
            }

            return (if (index < 128) index else -129 + (index - 127)).toByte()
        }
    }

    fun matchColorToMap(color: org.bukkit.Color): Color {
        if (color.alpha < 128) {
            return colors[0]
        }
        else {
            var color = colors[0]
            var best = -1.0

            for (i in 4..colors.size) {
                val distance = getDistance(color, colors[i -1])
                if (distance < best || best == -1.0) {
                    best = distance
                    color = colors[i]
                }
            }

            return color
        }
    }

    fun matchColorToEscapeChar(color: org.bukkit.Color): String {
        if (color.alpha < 128) {
            return escapeCharacters[0]
        }
        else {
            var index = 0
            var best = -1.0

            for (i in 4..colors.size) {
                val distance = getDistance(color, colors[i -1])
                if (distance < best || best == -1.0) {
                    best = distance
                    index = i
                }
            }

            return escapeCharacters[index - 1]
        }
    }


    fun getColor(index: Byte): Color {
        return colors[if (index >= 0) index.toInt() else index + 256]
    }

	fun getHighestY(world: World, x: Int, z: Int): Block {
		var i = 255
		while (i > 0) {
			val block = Location(world, x.toDouble(), i.toDouble(), z.toDouble()).block
			if (block.type != Material.AIR)
				return block
			i--
		}
		return Location(world, x.toDouble(), i.toDouble(), z.toDouble()).block
	}
